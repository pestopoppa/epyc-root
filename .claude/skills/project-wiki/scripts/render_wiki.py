#!/usr/bin/env python3
"""KT-4: readable compiled wiki pages, a generated edge list, and an optional Obsidian view.

Subcommands (all output is generated; nothing here is hand-maintained):

* ``restructure PAGE...`` -- put the topical sections first and move the "Last compiled" history
  and every ``## Compiled Update`` section into a trailing ``## Compile Log`` (headings demoted one
  level). No text and no provenance link is dropped: the transform is a reordering, and
  ``--check`` proves the multiset of non-heading lines is unchanged. Idempotent; a page that
  gains new Compiled Update sections above its log has them folded into the top of the log.
* ``index`` -- regenerate the one-line current-state summary per page inside the
  ``<!-- kt4:summaries -->`` block of ``wiki/INDEX.md`` (the index-first pattern).
* ``edges`` -- JSON edge list: wiki markdown links, ``intake-NNN[#claim]`` citations, ledger
  ``depends_on_entry`` edges and handoff-index ``Deps`` edges. Default output is outside the
  tracked tree.
* ``vault`` -- an Obsidian-compatible stub vault (copies of the pages with relative ``.md`` links
  rewritten to ``[[wikilinks]]``), default under ``/mnt/raid0/llm/tmp/``.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
WIKI = ROOT / "wiki"
ADMIN = {"INDEX.md", "SCHEMA.md"}
LOG_HEADING = "## Compile Log"
GEN_DIR = Path("/mnt/raid0/llm/tmp/wiki-kt4")
BEGIN, END = "<!-- kt4:summaries:begin -->", "<!-- kt4:summaries:end -->"
_LINK = re.compile(r"\[([^\]]*)\]\(([^)\s]+)\)")
_INTAKE = re.compile(r"intake-(\d+)(?:#(\d+|record))?")


# ------------------------------------------------------------------ restructure

def _split(lines: list[str]) -> tuple[list[str], list[list[str]]]:
    head, sections, cur = [], [], None
    for ln in lines:
        if ln.startswith("## "):
            cur = [ln]
            sections.append(cur)
        elif cur is None:
            head.append(ln)
        else:
            cur.append(ln)
    return head, sections


def _demote(sec: list[str]) -> list[str]:
    return ["#" + ln if re.match(r"#{2,5} ", ln) else ln for ln in sec]


def restructure_text(text: str) -> str:
    head, sections = _split(text.splitlines())
    last_compiled = [ln for ln in head if ln.startswith("**Last compiled**")]
    head = [ln for ln in head if not ln.startswith("**Last compiled**")]
    topical, updates, log = [], [], []
    for sec in sections:
        if sec[0].startswith("## Compiled Update"):
            updates.append(_demote(sec))
        elif sec[0].strip() == LOG_HEADING:
            log = sec[1:]
        else:
            topical.append(sec)
    while head and not head[-1].strip():
        head.pop()
    out = head + [""]
    for sec in topical:
        out += sec
    while out and not out[-1].strip():
        out.pop()
    out += ["", LOG_HEADING, "",
            "_Generated by `render_wiki.py restructure`: compile history, newest first. "
            "The sections above are the current state._", ""]
    out += last_compiled + ([""] if last_compiled else [])
    for sec in updates:
        out += sec
    # an existing log keeps its order, minus the banner lines this function writes itself
    kept = [ln for ln in log if not ln.startswith("_Generated by `render_wiki.py")]
    while kept and not kept[0].strip():
        kept.pop(0)
    if kept and out[-1].strip():
        out.append("")
    out += kept
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out) + "\n"


def _content_multiset(text: str) -> Counter:
    return Counter(re.sub(r"^#+ ", "", ln).strip() for ln in text.splitlines()
                   if ln.strip() and not ln.startswith("_Generated by `render_wiki.py")
                   and ln.strip() != LOG_HEADING)


def check_lossless(before: str, after: str) -> bool:
    return _content_multiset(before) == _content_multiset(after)


# ------------------------------------------------------------------ index summaries

def page_summary(text: str) -> str:
    """First sentence of `## Summary` (or of the first topical paragraph), links kept."""
    head, sections = _split(text.splitlines())
    cands = [s for s in sections if s[0].strip().lower() in ("## summary", "## overview")]
    cands += [s for s in sections if not s[0].startswith(("## Compiled Update", LOG_HEADING))]
    for sec in cands:
        para = []
        for ln in sec[1:]:
            if ln.strip() and not ln.startswith(("#", "|", "<!--", ">")):
                para.append(ln.strip().lstrip("-* "))
            elif para:
                break
        if para:
            s = " ".join(para)
            m = re.search(r"(?<=[.!?])\s+(?=[A-Z*])", s)
            s = s[: m.start()] if m else s
            return s if len(s) <= 300 else s[:297].rstrip() + "..."
    return "(no summary section)"


def render_index(index_text: str, pages: dict[str, str]) -> str:
    lines = [BEGIN, "## Current state per page (generated)", "",
             "_One line per page from its Summary section; regenerate with "
             "`render_wiki.py index`. History lives in each page's Compile Log._", ""]
    for name in sorted(pages):
        title = pages[name].splitlines()[0].lstrip("# ").strip() if pages[name] else name
        lines.append(f"- [{title}]({name}) — {page_summary(pages[name])}")
    block = "\n".join(lines + ["", END])
    if BEGIN in index_text and END in index_text:
        a, b = index_text.index(BEGIN), index_text.index(END) + len(END)
        return index_text[:a] + block + index_text[b:]
    first_nl = index_text.index("\n") + 1
    return index_text[:first_nl] + "\n" + block + "\n" + index_text[first_nl:]


# ------------------------------------------------------------------ edges

def wiki_edges(wiki: Path) -> list[dict]:
    edges = []
    for p in sorted(wiki.glob("*.md")):
        text = p.read_text(encoding="utf-8", errors="ignore")
        src = f"wiki/{p.name}"
        for _, target in _LINK.findall(text):
            if target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            path = target.split("#", 1)[0]
            if path:
                dst = (Path("wiki") / path).as_posix()
                edges.append({"src": src, "dst": _normpath(dst), "kind": "md_link"})
        for num, claim in sorted(set(_INTAKE.findall(text))):
            edges.append({"src": src, "dst": f"intake-{num}" + (f"#{claim}" if claim else ""),
                          "kind": "intake_citation"})
    return edges


def _normpath(p: str) -> str:
    parts: list[str] = []
    for x in p.split("/"):
        if x == "..":
            if parts:
                parts.pop()
        elif x not in ("", "."):
            parts.append(x)
    return "/".join(parts)


def ledger_edges(ledger: Path) -> list[dict]:
    seen, edges = set(), []
    if not ledger.exists():
        return edges
    with ledger.open(encoding="utf-8") as fh:
        for ln in fh:
            if '"depends_on_entry"' not in ln:
                continue
            a = json.loads(ln).get("frame", {}).get("assertion", {})
            key = (a.get("claim_id"), a.get("depends_on_entry"))
            if all(key) and key not in seen:
                seen.add(key)
                edges.append({"src": key[0], "dst": key[1], "kind": "ledger_depends_on"})
    return edges


def handoff_edges(active: Path) -> list[dict]:
    edges = []
    for idx in sorted(active.glob("*-index.md")):
        for ln in idx.read_text(encoding="utf-8", errors="ignore").splitlines():
            cells = [c.strip() for c in ln.strip().strip("|").split("|")]
            if len(cells) != 5 or not re.match(r"[A-Z]+-\d+", cells[0]):
                continue
            m = _LINK.search(cells[2])
            src = f"handoffs/active/{m.group(2)}" if m else cells[0]
            for dep in re.findall(r"[A-Z][A-Z0-9]*-\d+[a-z]?", cells[4]):
                edges.append({"src": src, "dst": dep, "kind": "handoff_dep", "row": cells[0]})
    return edges


def build_edges(ledger: Path) -> dict:
    edges = wiki_edges(WIKI) + ledger_edges(ledger) + handoff_edges(ROOT / "handoffs" / "active")
    return {"schema": "epyc.wiki/edges/v1",
            "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "counts": dict(Counter(e["kind"] for e in edges)), "edges": edges}


# ------------------------------------------------------------------ vault

def build_vault(out: Path) -> int:
    out.mkdir(parents=True, exist_ok=True)
    n = 0
    for p in sorted(WIKI.glob("*.md")):
        text = p.read_text(encoding="utf-8", errors="ignore")

        def wl(m: re.Match) -> str:
            label, target = m.group(1), m.group(2)
            path, _, frag = target.partition("#")
            if "/" in path or not path.endswith(".md"):
                return m.group(0)
            stem = path[:-3]
            return f"[[{stem}{'#' + frag if frag else ''}|{label}]]"

        (out / p.name).write_text(_LINK.sub(wl, text), encoding="utf-8")
        n += 1
    (out / "README-generated.md").write_text(
        "Generated by render_wiki.py vault from wiki/. Do not edit; regenerate.\n")
    return n


# ------------------------------------------------------------------ main

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("restructure")
    r.add_argument("pages", nargs="+")
    r.add_argument("--check", action="store_true", help="report only; exit 1 if a page would change")
    sub.add_parser("index")
    e = sub.add_parser("edges")
    e.add_argument("--out", default=str(GEN_DIR / "edges.json"))
    e.add_argument("--ledger", default="/mnt/raid0/llm/state/vidya/ledger.jsonl")
    v = sub.add_parser("vault")
    v.add_argument("--out", default=str(GEN_DIR / "obsidian-vault"))
    args = ap.parse_args(argv)

    if args.cmd == "restructure":
        rc = 0
        for name in args.pages:
            p = Path(name) if Path(name).exists() else WIKI / name
            before = p.read_text(encoding="utf-8")
            after = restructure_text(before)
            if not check_lossless(before, after):
                print(f"REFUSED {p}: restructure would change content", file=sys.stderr)
                rc = 2
                continue
            if before == after:
                print(f"unchanged {p}")
            elif args.check:
                print(f"would restructure {p}")
                rc = max(rc, 1)
            else:
                p.write_text(after, encoding="utf-8")
                print(f"restructured {p}")
        return rc
    if args.cmd == "index":
        pages = {p.name: p.read_text(encoding="utf-8", errors="ignore")
                 for p in sorted(WIKI.glob("*.md")) if p.name not in ADMIN}
        idx = WIKI / "INDEX.md"
        idx.write_text(render_index(idx.read_text(encoding="utf-8"), pages), encoding="utf-8")
        print(f"index: {len(pages)} page summaries")
        return 0
    if args.cmd == "edges":
        data = build_edges(Path(args.ledger))
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(data, indent=1) + "\n")
        print(f"edges: {out} {data['counts']}")
        return 0
    n = build_vault(Path(args.out))
    print(f"vault: {args.out} ({n} pages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
