"""P1c: cross-architecture golden fixtures, plus the end-to-end CLI path.

Spec: docs/design/vidya-pilot-spec.md §17.3 (determinism suite).

**What "cross-architecture" means here.** The values below are pinned constants, generated once on
x86-64 Linux. They are not regenerated by the test -- a test that recomputes its own expectation
proves only that the code agrees with itself. Running this same file unchanged on aarch64 (or any
other target) is the cross-architecture check: if canonical serialization, hashing, sorting, or the
fold's iteration order differ anywhere, a pinned value stops matching.

**Honest status:** executed on x86-64 only so far. The fixture IS the contract; the second
architecture is a matter of running it somewhere else, and until that happens the program handoff
carries P1c as open with this file named as the instrument.

Why the design should be architecture-independent in the first place, and where it could fail
anyway: floats are rejected outright (the one genuinely hard part of JCS number formatting is
therefore unreachable); Python string comparison is by code point and not locale-sensitive; every
collection that reaches a hash is explicitly sorted. The plausible regressions are a dict iteration
order leaking into an output, a locale-dependent sort creeping in, or a Python version changing
`json.dumps` escaping -- all of which these pins would catch.
"""

