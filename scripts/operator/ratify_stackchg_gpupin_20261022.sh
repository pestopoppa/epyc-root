#!/bin/bash
# ratify_stackchg_gpupin_20261022.sh -- operator signature AND landing for STACKCHG-GPUPIN-20261022:
# every thread of a CPU-pinned serving launch stays on its declared placement.
#
#   Review / dry run (default; pushes nothing, writes no receipt):
#     bash scripts/operator/ratify_stackchg_gpupin_20261022.sh --dry-run
#   Sign and land (the OPERATOR runs this, e.g. as ONE `!` command in Claude Code):
#     RATIFY_OPERATOR='<your name>' bash scripts/operator/ratify_stackchg_gpupin_20261022.sh --apply --attest RATIFY-STACKCHG-GPUPIN-20261022
#   Verify the post-state (read-only):
#     bash scripts/operator/ratify_stackchg_gpupin_20261022.sh --verify
#
# Package: artifacts/operator/stack-change-gpu-thread-pin-20261022/PACKAGE.md (read it first).
# Operator decisions already taken (2026-10-22): D1 = REFUSE a launch whose tasks escape the placement
# (no warn mode); D2 = re-check one GPU AutoKernel A/A at the next GPU AK window BEFORE the ROCr env
# knob is added to the AutoKernel loader (pending task GPS-PIN-3, not code). Open: D3 (cgroup cpuset),
# only if probe P1 fails.
#
# WHAT IT DOES (--apply), in this order, each step refusing on any mismatch:
#   1. checks the signer (typed --attest token; RATIFY_OPERATOR set, not a default/system/agent name);
#   2. verifies the sha256 of both code patches and of every root package file against the pins below;
#   3. for epyc-orchestrator and epyc-inference-research: a detached scratch worktree at a FRESH
#      origin/main, `git am` of the pinned patch (refuses if it does not apply -- the package is then
#      STALE and must be regenerated by its preparer, never reconciled here), a path allow-list check,
#      and the file-scoped tests for the touched modules;
#   4. for epyc-root: a detached scratch worktree at a fresh origin/main, a copy of the pinned package
#      files plus this script, each re-verified after the copy, and the receipt
#      artifacts/operator/receipts/RATIFY-STACKCHG-GPUPIN-20261022.json, all in ONE commit;
#   5. pushes orchestrator, then research, then root (the root commit carries the receipt), each as a
#      fast-forward of origin/main through scripts/coordination/serialized_push.py's push lock.
#
# WHAT IT DOES NOT DO: reload, start, stop or re-pin ANY process. The change takes effect for a role at
# that role's next reload, executed by the session that owns the role's inference, at its own boundary
# (CLAUDE.md, Process Management). No production kernel tree or kernel-store file is touched. No
# human-only path (coordination/session-bus/human_only_paths.yaml) is touched.
#
# IDEMPOTENT / RESUMABLE: a repo whose patch is already on origin/main (every patch subject present) is
# skipped; if a push is rejected because origin/main moved, nothing after it is pushed and a re-run
# resumes. Receipt already on origin/main + both patches landed -> "ALREADY RATIFIED", exit 0.
#
# ROLLBACK: `git revert` the landed orchestrator and research commits (shas are in the receipt), then the
# owners reload the same roles. No data, derived file or symlink changes.
set -euo pipefail
export PATH="/usr/bin:/bin:${PATH}"

SCRIPT_PATH="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
SRC_ROOT="${SRC_ROOT:-$(cd "$(dirname "$SCRIPT_PATH")/../.." && pwd)}"   # the checkout holding the package

GATE_ID="RATIFY-STACKCHG-GPUPIN-20261022"
PKG_REL="artifacts/operator/stack-change-gpu-thread-pin-20261022"
SCRIPT_REL="scripts/operator/ratify_stackchg_gpupin_20261022.sh"
RECEIPT_REL="artifacts/operator/receipts/$GATE_ID.json"

ORCH_REPO="${ORCH_REPO:-/mnt/raid0/llm/epyc-orchestrator}"
RESEARCH_REPO="${RESEARCH_REPO:-/mnt/raid0/llm/epyc-inference-research}"
ROOT_REPO="${ROOT_REPO:-/mnt/raid0/llm/epyc-root}"
ORCH_PY="${ORCH_PY:-/mnt/raid0/llm/epyc-orchestrator/.venv/bin/python}"
RESEARCH_PY="${RESEARCH_PY:-/mnt/raid0/llm/epyc-inference-research/.venv/bin/python}"
SYS_PY="/usr/bin/python3"
STAGE_PARENT="/mnt/raid0/llm/tmp"
LOCK_AGENT="operator-ratify-stackchg-gpupin"

# ---- pins (filled by the preparing agent; the operator verifies by reading them) ----
ORCH_PATCH="$PKG_REL/patches/stackchg-gpupin-20261022.orchestrator.patch"
RESEARCH_PATCH="$PKG_REL/patches/stackchg-gpupin-20261022.research.patch"
ROOT_PINS=(
  "4f8b1e1d1d61749ef716209793a49803912bb55e2a7fe814b3f1f934191b3a7e $PKG_REL/PACKAGE.md"
  "7a05a0de19436595381f7d714d6bc99013c3ea1c9ed629a7a54b4c48e49eeb23 $PKG_REL/intent.yaml"
  "4d5fdc5a0e5e917e24f525acb5c86c647e709fe38405a2ae18b708276002abd2 $ORCH_PATCH"
  "145f072df5272337f04ba59d4132c234a4cc7fcc44373606634d02148150c0f3 $RESEARCH_PATCH"
  "43eb94319f1c352a9cd3c5e98ef9141e3df46ce94b02a8c2183d358f8cc25dea $PKG_REL/patches/SHA256SUMS"
)
# paths each landed code commit may touch (anything else is refused)
ORCH_ALLOWED=(scripts/server/launch_affinity.py scripts/server/orchestrator_stack.py scripts/server/stack_commands.py
              scripts/attest/generate_attestation.py scripts/benchmark/serving_gate.py tests/unit/test_launch_affinity.py)
RESEARCH_ALLOWED=(scripts/kernel_rnd/autokernel/loop/launch_affinity.py scripts/kernel_rnd/autokernel/loop/serving.py
                  scripts/kernel_rnd/autokernel/loop/test_launch_affinity.py)
ORCH_TESTS=(tests/unit/test_launch_affinity.py tests/unit/test_launch_env_every_branch.py tests/unit/test_generate_attestation.py)
RESEARCH_TESTS=(scripts/kernel_rnd/autokernel/loop/test_launch_affinity.py scripts/kernel_rnd/autokernel/loop/test_recipe_env.py)

MODE="review"; ATTEST=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --dry-run|--review) MODE="review" ;;
    --apply)  MODE="apply" ;;
    --verify) MODE="verify" ;;
    --attest) shift; ATTEST="${1:-}" ;;
    *) echo "usage: $0 [--dry-run | --verify | --apply --attest $GATE_ID]" >&2; exit 64 ;;
  esac
  shift
done

say() { printf '%s\n' "$*"; }
die() { printf 'REFUSING: %s\n' "$*" >&2; exit 65; }
g() { local repo="$1"; shift; git -c safe.directory='*' -C "$repo" "$@"; }
sha_of() { sha256sum -- "$1" | awk '{print $1}'; }

for tool in git sha256sum awk "$SYS_PY"; do command -v "$tool" >/dev/null || die "$tool not available"; done
PUSHER="$ROOT_REPO/scripts/coordination/serialized_push.py"
[ -f "$PUSHER" ] || die "$PUSHER not found"
case "${ROOT_PINS[*]}" in *@@*) die "script was not finalised (unfilled pin)";; esac

# ---------------------------------------------------------------- 1. signer
if [ "$MODE" = "apply" ]; then
  [ "$ATTEST" = "$GATE_ID" ] || die "--apply requires the typed confirmation --attest $GATE_ID"
  # shellcheck source=/dev/null
  source "$ROOT_REPO/scripts/operator/lib/ratify_operator.sh"
  ratify_require_operator   # exits 65 on an unset/default/system/login/agent name
  say "signer: $RATIFY_OPERATOR"
fi

# ---------------------------------------------------------------- 2. pins
say "== pins (source checkout $SRC_ROOT) =="
for pin in "${ROOT_PINS[@]}"; do
  want="${pin%% *}"; rel="${pin#* }"
  [ -f "$SRC_ROOT/$rel" ] || die "missing package file $rel"
  have="$(sha_of "$SRC_ROOT/$rel")"
  [ "$have" = "$want" ] || die "$rel sha256 $have != pinned $want (package changed after preparation)"
  say "  ok  $rel  $have"
done
SCRIPT_SHA="$(sha_of "$SCRIPT_PATH")"
say "  this script sha256 $SCRIPT_SHA (recorded in the receipt)"

# ---------------------------------------------------------------- state vs origin/main
for r in "$ORCH_REPO" "$RESEARCH_REPO" "$ROOT_REPO"; do
  g "$r" fetch -q origin main || die "cannot fetch origin main in $r"
done
subjects() { # unfolded, decoded commit subjects of an mbox patch series (what `git log %s` prints)
  "$SYS_PY" - "$1" <<'PY'
import mailbox, re, sys
from email.header import decode_header, make_header
for msg in mailbox.mbox(sys.argv[1]):
    subj = " ".join(str(make_header(decode_header(msg["Subject"] or ""))).split())
    print(re.sub(r"^\[PATCH[^\]]*\]\s*", "", subj))
PY
}
patch_landed() { # repo patch -> yes|no  (every patch subject in the last 2000 origin/main subjects)
  local repo="$1" patch="$2" log s
  log="$(g "$repo" log origin/main -n 2000 --format=%s)"
  while IFS= read -r s; do
    [ -n "$s" ] || continue
    [ "$(grep -Fxc -- "$s" <<<"$log" || true)" -gt 0 ] || { echo no; return; }
  done < <(subjects "$patch")
  echo yes
}
ORCH_LANDED="$(patch_landed "$ORCH_REPO" "$SRC_ROOT/$ORCH_PATCH")"
RES_LANDED="$(patch_landed "$RESEARCH_REPO" "$SRC_ROOT/$RESEARCH_PATCH")"
RECEIPT_LANDED=no
g "$ROOT_REPO" cat-file -e "origin/main:$RECEIPT_REL" 2>/dev/null && RECEIPT_LANDED=yes
say "  orchestrator patch on origin/main: $ORCH_LANDED; research patch: $RES_LANDED; receipt: $RECEIPT_LANDED"

if [ "$MODE" = "verify" ]; then
  ok=1
  [ "$ORCH_LANDED" = yes ] || { say "  FAIL  orchestrator patch is not on origin/main"; ok=0; }
  [ "$RES_LANDED" = yes ]  || { say "  FAIL  research patch is not on origin/main"; ok=0; }
  [ "$RECEIPT_LANDED" = yes ] || { say "  FAIL  $RECEIPT_REL is not on origin/main"; ok=0; }
  [ "$ok" -eq 1 ] && { say "VERIFIED: $GATE_ID landed (code + receipt). Now run the post-apply checks in PACKAGE.md section 5."; exit 0; }
  exit 1
fi
if [ "$ORCH_LANDED$RES_LANDED$RECEIPT_LANDED" = "yesyesyes" ]; then
  say "ALREADY RATIFIED: both patches and $RECEIPT_REL are on origin/main. Nothing to do."; exit 0
fi
[ "$RECEIPT_LANDED" = no ] || die "$RECEIPT_REL is on origin/main but the code is not fully landed. Resolve by hand."

# ---------------------------------------------------------------- push locks free (read-only)
for r in "$ORCH_REPO" "$RESEARCH_REPO" "$ROOT_REPO"; do
  st="$("$SYS_PY" "$PUSHER" --agent "$LOCK_AGENT" --repo "$r" --lock-name push --status 2>&1 || true)"
  case "$st" in *FREE*) say "  ok  push lock FREE for $r" ;; *) die "push lock for $r is not free: $st" ;; esac
done

# ---------------------------------------------------------------- 3-4. stage in scratch worktrees
STAGE="$(mktemp -d "$STAGE_PARENT/stackchg-gpupin-land.XXXXXX")"
WT_ADDED=()
ROOT_WT="$STAGE/root"
ROOT_COPIED=()
cleanup() {
  local wt rel
  for wt in "${WT_ADDED[@]}"; do
    local repo="${wt%%|*}" path="${wt#*|}"
    [ -d "$path" ] || continue
    g "$path" am --abort >/dev/null 2>&1 || true          # only ever inside OUR scratch worktree
    if [ "$path" = "$ROOT_WT" ]; then
      # files this run copied in and never committed (dry run / refusal): remove exactly those
      g "$path" reset -q >/dev/null 2>&1 || true
      for rel in "${ROOT_COPIED[@]}"; do
        g "$path" ls-files --error-unmatch -- "$rel" >/dev/null 2>&1 || rm -f -- "$path/$rel"
      done
      find "$path/$PKG_REL" -depth -type d -empty -delete 2>/dev/null || true
    fi
    g "$repo" worktree remove "$path" >/dev/null 2>&1 || say "NOTE: scratch worktree left at $path (inspect, then: git -C $repo worktree remove $path)"
  done
  rm -f -- "$STAGE"/*.tests.txt
  rmdir "$STAGE" 2>/dev/null || true
}
trap cleanup EXIT

STAGED_SHA=""
stage_code() { # name repo patch py allowed-var tests-var -> sets STAGED_SHA (runs in THIS shell, never $(...))
  local name="$1" repo="$2" patch="$3" py="$4"; local -n allowed="$5" tests="$6"
  local wt="$STAGE/$name" base bad="" f a okp
  g "$repo" worktree add -q --detach "$wt" origin/main || die "$name: cannot add a scratch worktree"
  WT_ADDED+=("$repo|$wt")
  base="$(g "$wt" rev-parse HEAD)"
  g "$wt" am -q "$SRC_ROOT/$patch" >/dev/null 2>&1 || { g "$wt" am --abort >/dev/null 2>&1 || true;
    die "STALE: $patch no longer applies to $name origin/main ($base). The preparer must REGENERATE it; do not reconcile at signing."; }
  while IFS= read -r f; do
    [ -n "$f" ] || continue; okp=0
    for a in "${allowed[@]}"; do [ "$f" = "$a" ] && okp=1; done
    [ "$okp" -eq 1 ] || bad="$bad $f"
  done < <(g "$wt" diff --name-only "$base" HEAD)
  [ -z "$bad" ] || die "$name: patch touches paths outside the allow-list:$bad"
  say "  ok  $name: $patch applies on origin/main $base -> $(g "$wt" rev-parse --short HEAD), allowed paths only"
  [ -x "$py" ] || die "$name: test interpreter $py missing"
  (cd "$wt" && nice -n 19 timeout 900 "$py" -m pytest -q -p no:cacheprovider "${tests[@]}" >"$STAGE/$name.tests.txt" 2>&1) \
    || { tail -20 "$STAGE/$name.tests.txt" >&2; die "$name: file-scoped tests FAILED on the staged tree"; }
  say "  ok  $name tests: $(tail -1 "$STAGE/$name.tests.txt")"
  STAGED_SHA="$(g "$wt" rev-parse HEAD)"
}
say "== staging =="
ORCH_SHA=""; RES_SHA=""
if [ "$ORCH_LANDED" != yes ]; then
  stage_code orchestrator "$ORCH_REPO" "$ORCH_PATCH" "$ORCH_PY" ORCH_ALLOWED ORCH_TESTS; ORCH_SHA="$STAGED_SHA"
fi
if [ "$RES_LANDED" != yes ]; then
  stage_code research "$RESEARCH_REPO" "$RESEARCH_PATCH" "$RESEARCH_PY" RESEARCH_ALLOWED RESEARCH_TESTS; RES_SHA="$STAGED_SHA"
fi

g "$ROOT_REPO" worktree add -q --detach "$ROOT_WT" origin/main || die "root: cannot add a scratch worktree"
WT_ADDED+=("$ROOT_REPO|$ROOT_WT")
for pin in "${ROOT_PINS[@]}"; do
  want="${pin%% *}"; rel="${pin#* }"
  if [ -e "$ROOT_WT/$rel" ] && [ "$(sha_of "$ROOT_WT/$rel")" != "$want" ]; then
    die "root: origin/main already has a DIFFERENT $rel; refusing to overwrite it"
  fi
  mkdir -p "$(dirname "$ROOT_WT/$rel")"; cp -- "$SRC_ROOT/$rel" "$ROOT_WT/$rel"; ROOT_COPIED+=("$rel")
  [ "$(sha_of "$ROOT_WT/$rel")" = "$want" ] || die "root: $rel changed during the copy"
done
mkdir -p "$(dirname "$ROOT_WT/$SCRIPT_REL")"; cp -- "$SCRIPT_PATH" "$ROOT_WT/$SCRIPT_REL"; ROOT_COPIED+=("$SCRIPT_REL" "$RECEIPT_REL")
[ "$(sha_of "$ROOT_WT/$SCRIPT_REL")" = "$SCRIPT_SHA" ] || die "root: script changed during the copy"
say "  ok  root: package files + script staged on origin/main $(g "$ROOT_WT" rev-parse --short HEAD)"

if [ "$MODE" = "review" ]; then
  say ""
  say "DRY RUN -- nothing was pushed, no receipt was written. --apply would:"
  [ "$ORCH_LANDED" = yes ] || say "  1. push orchestrator ${ORCH_SHA:0:12} (pinned patch on fresh origin/main) under the push lock"
  [ "$RES_LANDED" = yes ]  || say "  2. push research ${RES_SHA:0:12} (pinned patch on fresh origin/main) under the push lock"
  say "  3. commit package + script + $RECEIPT_REL on fresh root origin/main and push it under the push lock"
  say "  It reloads NOTHING. The scratch worktrees are removed on exit."
  say "DRY-RUN OK: $GATE_ID -- all preconditions hold."
  exit 0
fi

# ---------------------------------------------------------------- 5. push (apply)
push_locked() { # name repo-for-lock worktree
  local name="$1" repo="$2" wt="$3" tokdir tok rc=0
  tokdir="$(mktemp -d "$STAGE_PARENT/stackchg-gpupin-push-token.XXXXXX")"; chmod 700 "$tokdir"; tok="$tokdir/lease.token"
  "$SYS_PY" "$PUSHER" --agent "$LOCK_AGENT" --repo "$repo" --lock-name push --acquire --token-file "$tok" >/dev/null \
    || { rmdir "$tokdir" 2>/dev/null; die "$name: could not take the push lock"; }
  AGENT_ID="$LOCK_AGENT" EPYC_PUSH_LOCK_HOLDER="$LOCK_AGENT" git -c safe.directory='*' -C "$wt" push origin HEAD:refs/heads/main || rc=$?
  "$SYS_PY" "$PUSHER" --agent "$LOCK_AGENT" --repo "$repo" --lock-name push --release --token-file "$tok" >/dev/null \
    || say "WARN: $name push lock release failed -- check serialized_push.py --status"
  rm -f "$tok"; rmdir "$tokdir" 2>/dev/null || true
  [ "$rc" -eq 0 ] || die "$name: git push rejected (rc=$rc; origin/main probably moved). Nothing after this was pushed; re-run to resume."
  say "  pushed $name $(g "$wt" rev-parse --short HEAD) -> origin/main"
}
say ""; say "== landing =="
[ "$ORCH_LANDED" = yes ] || push_locked orchestrator "$ORCH_REPO" "$STAGE/orchestrator"
[ "$RES_LANDED" = yes ]  || push_locked research "$RESEARCH_REPO" "$STAGE/research"
g "$ORCH_REPO" fetch -q origin main; g "$RESEARCH_REPO" fetch -q origin main
[ "$(patch_landed "$ORCH_REPO" "$SRC_ROOT/$ORCH_PATCH")" = yes ] || die "orchestrator patch not on origin/main after the push"
[ "$(patch_landed "$RESEARCH_REPO" "$SRC_ROOT/$RESEARCH_PATCH")" = yes ] || die "research patch not on origin/main after the push"
[ -n "$ORCH_SHA" ] || ORCH_SHA="(landed before this run; see origin/main log)"
[ -n "$RES_SHA" ]  || RES_SHA="(landed before this run; see origin/main log)"

mkdir -p "$ROOT_WT/artifacts/operator/receipts"
[ ! -e "$ROOT_WT/$RECEIPT_REL" ] || die "$RECEIPT_REL already exists on origin/main (token spent)"
RECEIPT_ABS="$ROOT_WT/$RECEIPT_REL" GATE_ID="$GATE_ID" OPERATOR="$RATIFY_OPERATOR" O_SHA="$ORCH_SHA" R_SHA="$RES_SHA" \
SCRIPT_SHA="$SCRIPT_SHA" PINS="$(printf '%s\n' "${ROOT_PINS[@]}")" "$SYS_PY" - <<'PY'
import datetime, json, os
