    "package": "artifacts/operator/stack-change-gpu-thread-pin-20261022/PACKAGE.md",
    "decision": ("STACKCHG-GPUPIN-20261022: every task of a CPU-pinned serving launch stays inside its declared "
                 "placement -- HSA_OVERRIDE_CPU_AFFINITY_DEBUG=0 on pinned stack launches, post-health re-pin of "
                 "OUR pid, refusal on a remaining escape, per-task affinity attestation in status/attestation."),
    "decisions": {
        "D1": "REFUSE the launch when a task still escapes after re-pin; no warn mode (operator 2026-10-22)",
