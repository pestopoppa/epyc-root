        "D3": "OPEN -- cgroup-v2 cpuset only if probe P1 fails",
    },
    "landed": {
        "epyc-orchestrator": {"commit": e["O_SHA"], "ref": "origin/main"},
        "epyc-inference-research": {"commit": e["R_SHA"], "ref": "origin/main"},
