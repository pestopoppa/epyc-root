ROOT_PATHS=("$SCRIPT_REL" "$RECEIPT_REL")
for pin in "${ROOT_PINS[@]}"; do ROOT_PATHS+=("${pin#* }"); done
g "$ROOT_WT" add -- "${ROOT_PATHS[@]}"
g "$ROOT_WT" commit -q -m "RATIFIED $GATE_ID: deterministic host-thread pinning for every pinned serving launch (signed by $RATIFY_OPERATOR)" \
  -m "Package $PKG_REL; orchestrator ${ORCH_SHA:0:12}, research ${RES_SHA:0:12} landed; receipt $RECEIPT_REL. Reloads: none (owners reload at their own boundary)." \
  || die "root: commit failed (a pre-commit hook refused it?); orchestrator/research are landed, re-run to resume the root step"
push_locked root "$ROOT_REPO" "$ROOT_WT"

cat <<EOF

