try:
    text=pathlib.Path(sys.argv[1]).read_text()
    pid, birth, cap=sys.argv[2:]
    wait='while ps -o pid= -p %s >/dev/null 2>&1 && predecessor_alive %s %s; do sleep 30; done' % (pid,pid,birth)
    final='if predecessor_alive %s %s; then log "predecessor identity uncertain or still live; refusing startup"; exit 1; fi' % (pid,birth)
    calls=re.findall(r'(?m)^while ps -o pid= -p (\d+) .*&& predecessor_alive (\d+) (\d+); do sleep 30; done$',text)
    guards=re.findall(r'(?m)^if predecessor_alive (\d+) (\d+); then ',text)
    caps=re.findall(r"(?m)^P3=\$\(date -u -d '([^']+)'",text)
    ok=wait in text.splitlines() and final in text.splitlines() and calls==[(pid,pid,birth)] and guards==[(pid,birth)] and caps==[cap]
    # No stale executable predecessor literal/path may survive a rewrite.
    active='\n'.join(line for line in text.splitlines() if not line.lstrip().startswith('#'))
    ok=ok and not re.search(r"pathlib\.Path\('/proc/\d+'\)",active)
    ok=ok and re.findall(r'\bpredecessor_alive\s+(\d+)\s+(\d+)',active)==[(pid,birth),(pid,birth)]
    sys.exit(0 if ok else 1)
except (OSError, ValueError, IndexError): sys.exit(1)
