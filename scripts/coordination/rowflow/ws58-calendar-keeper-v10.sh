}
gpu_succession() {
  local cur n md nd next pid birth cap1 dst mk p3 now oldwait oldbirth prevfile prevpid
  cur=$(ls ${F}grant-gpu-????-v[0-9]*.sh 2>/dev/null | sed -n 's/.*grant-gpu-\([0-9]\{4\}\)-v\([0-9]*\)\.sh$/\2 \1/p' | sort -n | tail -1)
  [ -n "$cur" ] || return 0
  n=${cur% *}; md=${cur#* }; next=$((n+1))
  local curname="grant-gpu-$md-v$n"
  p3=$(sed -n "s/^P3=\$(date -u -d '\([^']*\)'.*/\1/p" "${F}$curname.sh" | head -1); [ -n "$p3" ] || return 0
  now=$(date -u +%s)
  if writer_alive "${F}$curname.pid" "$curname.sh" && [ $(( $(date -u -d "$p3" +%s) - now )) -gt 10800 ]; then return 0; fi
  if [ ! -e "${F}$curname.pid" ] && [ "$(date -u -d "$p3" +%s)" -gt "$now" ]; then
    # Highest discovered file may be a failed partial generation from a previous tick.
    # Resolve its expected predecessor from the previous VERSION, never trust its own wait line.
    prevfile=$(ls ${F}grant-gpu-????-v$((n-1)).pid 2>/dev/null | sort | tail -1)
    [ -n "$prevfile" ] || { log "REFUSE gpu candidate $curname: no predecessor pid file"; return 0; }
    prevpid=$(cat "$prevfile" 2>/dev/null) || return 0
    birth=$(gpu_identity "$prevpid" "${prevfile%.pid}.sh") || { log "REFUSE gpu candidate $curname: predecessor identity unavailable"; return 0; }
    gpu_candidate_ok "${F}$curname.sh" "$prevpid" "$birth" "$p3" || { log "REFUSE gpu candidate $curname: wait/birth/cap validation failed"; return 0; }
    mk="${S}started-$curname"; [ -e "$mk" ] && return 0
    log "START gpu writer ${F}$curname.sh (validated never started)"; [ $DRY = 1 ] && return 0
    touch "$mk"; (cd /mnt/raid0/llm/tmp/compute-flags && setsid bash "${F}$curname.sh" </dev/null >/dev/null 2>&1 &); return 0
  fi
  cap1=$(date -u -d "$p3 +1 day" +%Y-%m-%dT%H:%M:%SZ)
  [ "$(date -u -d "$cap1" +%s)" -le "$STOP_AT" ] || { log "SUCCESSION: next gpu cap $cap1 is past keeper stop; not generating"; return 0; }
  nd=$(date -u -d "$p3" +%m%d)
  dst="${F}grant-gpu-$nd-v$next.sh"; mk="${S}started-grant-gpu-$nd-v$next"
  [ -e "$mk" ] && return 0
  pid=$(cat "${F}$curname.pid" 2>/dev/null); [[ "$pid" =~ ^[0-9]+$ ]] || return 0
  if writer_alive "${F}$curname.pid" "$curname.sh"; then
    birth=$(gpu_identity "$pid" "${F}$curname.sh") || { log "REFUSE gpu succession $curname: current writer identity unavailable"; return 0; }
  else
    # v7d: current writer already DEAD (it hit its cap, crashed, or was stopped). Nothing to wait for, so the
    # successor gets birth 0: predecessor_alive is false for a missing /proc entry and for any reused pid.
    birth=0; log "SUCCESSION: current gpu writer $curname (pid $pid) is dead; successor will not wait"
  fi
  oldwait=$(sed -n 's/^while ps -o pid= -p \([0-9]*\) .*&& predecessor_alive [0-9]* \([0-9]*\); do sleep 30; done$/\1/p' "${F}$curname.sh" | head -1)
  oldbirth=$(sed -n 's/^while ps -o pid= -p [0-9]* .*&& predecessor_alive [0-9]* \([0-9]*\); do sleep 30; done$/\1/p' "${F}$curname.sh" | head -1)
  [[ "$oldwait" =~ ^[0-9]+$ && "$oldbirth" =~ ^[0-9]+$ ]] || { log "REFUSE gpu succession $curname: source wait format unknown"; return 0; }
  if [ ! -e "$dst" ]; then
    log "GENERATE $dst from $curname.sh (cap $p3->$cap1; predecessor $pid birth $birth)"
    if [ $DRY = 0 ]; then
      sed -e "s/grant-gpu-$md-v$n/grant-gpu-$nd-v$next/g" -e "s/$p3/$cap1/g" \
          -e "s/^while ps -o pid= -p $oldwait /while ps -o pid= -p $pid /" \
          -e "s/predecessor_alive $oldwait $oldbirth/predecessor_alive $pid $birth/g" \
          -e "s/^log \"v$((n-1)) ($oldwait) gone; v$n starting\"/log \"v$n ($pid) gone; v$next starting\"/" \
          -e "s/^log \"armed v$n /log \"armed v$next /" \
          -e "1a # v$next (ws58-calendar-keeper $(date -u +%FT%TZ)): waits for v$n ($pid birth $birth)." \
          "${F}$curname.sh" | tee "$dst" >/dev/null
      chmod +x "$dst"
    fi
  fi
  # Deliberately OUTSIDE the creation branch: a failed existing file must never start later.
  [ $DRY = 1 ] && return 0
  gpu_candidate_ok "$dst" "$pid" "$birth" "$cap1" || { log "REFUSE gpu candidate $dst: wait/birth/cap validation failed"; return 0; }
  log "START gpu writer $dst (validated predecessor $pid birth $birth)"
  touch "$mk"
  (cd /mnt/raid0/llm/tmp/compute-flags && setsid bash "$dst" </dev/null >/dev/null 2>&1 &)
}

# ---------- 4. idle alarm ----------
idle_alarm() {
  local hold st r n last now fired=""
  hold=$(ls ${F}HOLD_* 2>/dev/null | head -1)
  st=$($RL status 2>/dev/null)
  now=$(date -u +%s)
  for r in q0 q1 q2 q3 gpu-quiet; do
    if [ -z "$hold" ] && echo "$st" | awk -v r="$r" '$1==r && $2=="free"{f=1} END{exit !f}'; then
      n=$(( $(cat "${S}free-$r" 2>/dev/null || echo 0) + 1 ))
    else n=0; fi
    if [ $DRY = 1 ]; then echo "[dry-run] idle-check $r: consecutive_free would be $n${hold:+ (HOLD present: $hold)}"; else put "${S}free-$r" "$n"; fi
    if [ $n -ge 2 ]; then
      last=$(cat "${S}alarm-$r" 2>/dev/null || echo 0)
      [ $(( now - last )) -ge 900 ] && fired="$fired $r"
    fi
  done
  fired=${fired# }; [ -n "$fired" ] || return 0
  local ts; ts=$(date -u +%FT%TZ)
  log "IDLE-ALARM free for >=2 checks: $fired"
  [ $DRY = 1 ] && return 0
  for r in $fired; do put "${S}alarm-$r" "$now"; done
  add "${F}ws58-keeper-alerts.jsonl" "{\"ts\":\"$ts\",\"from\":\"ws58-calendar-keeper\",\"kind\":\"idle\",\"regions\":\"$fired\",\"checks\":2,\"interval_s\":120}"
  python3 -I - "$ts" "$fired" <<'PY'
import json,sys
p='/mnt/raid0/llm/tmp/codex-ni-20261024-scheduling/OWNER-REPLY.json'
d=json.load(open(p))
d['updates'].append({"ts":sys.argv[1],"from":"workspace-58 (calendar keeper)","subject":"IDLE NOW: "+sys.argv[2],"body":"Standing order: deliver READY rows for these idle regions now; keep working the inference backlog continuously."})
json.dump(d,open(p,'w'),indent=1)
PY
  touch /mnt/raid0/llm/tmp/codex-ni-20261024-scheduling/OWNER-RESPONSE-CHANGED.flag
  printf '\n## %s ws58 calendar keeper → refactor\n- IDLE NOW: %s. Standing order: deliver READY rows for these regions now; keep working continuously.\n' "$ts" "$fired" >> /mnt/raid0/llm/tmp/refactor-01a16fc3/compute-coordination-20261026/owner-reply.md
}

