alive() { [ -n "${1:-}" ] && ps -o pid= -p "$1" >/dev/null 2>&1; }
# alive AND its argv names the script (guards against pid reuse)
writer_alive() { local p; p=$(cat "$1" 2>/dev/null) || return 1; alive "$p" && ps -o args= -p "$p" 2>/dev/null | grep -qF "$2"; }
