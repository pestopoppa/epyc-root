rowflow_tick() {
  local l rid regs
  [ -f "$ROWFLOW" ] || { log "ROWFLOW: $ROWFLOW missing"; return 0; }
  [ -n "$(ls ${F}HOLD_* 2>/dev/null)" ] && { log "ROWFLOW: HOLD present; not arming / dry-running"; return 0; }
  if [ $DRY = 1 ]; then
    python3 -I "$ROWFLOW" --flags "$F" list 2>&1 | while IFS= read -r l; do log "ROW $l"; done
    python3 -I "$ROWFLOW" --flags "$F" dryrun-pick 2>&1 | while IFS= read -r l; do log "DRYRUN-WOULD-START $l"; done
    return 0
  fi
  python3 -I "$ROWFLOW" --flags "$F" arm-tick 2>&1 | while IFS= read -r l; do [ -n "$l" ] && log "ROW-ARM $l"; done
  python3 -I "$ROWFLOW" --flags "$F" dryrun-pick 2>&1 | while IFS=$'\t' read -r rid regs; do
    [ -n "$rid" ] || continue
    case "$rid" in REFUSED*|Traceback*) log "DRYRUN-PICK-ERROR $rid $regs"; continue;; esac
    log "DRYRUN-START $rid regions=$regs"
    mkdir -p "${F}dryrun/$rid"
    (cd /mnt/raid0/llm/tmp/compute-flags && setsid bash -c "r=\$(python3 -I '$ROWFLOW' --flags '$F' dryrun-run '$rid' --regions '$regs' 2>>'${F}dryrun/$rid/keeper.err'); echo \"\$(date -u +%FT%TZ) DRYRUN-RESULT \$r\" >> '$KLOG'" </dev/null >/dev/null 2>&1 &)
  done
}

