# ---------- 3. writer succession ----------
quarter_succession() {
  local last next cap0 cap1 s0 src dst mk
  [ -n "$(live_quarter_writers)" ] && return 0
  last=$(newest_writer_day); [ -n "$last" ] || return 0
  next=$(date -u -d "${last:0:4}-${last:4:2}-${last:6:2} +1 day" +%Y%m%d)
  dst="${F}grant-ws58-quarters-$next.sh"; mk="${S}started-quarters-$next"
  [ -e "$mk" ] && return 0
  if writer_alive "${F}grant-ws58-quarters-$last.pid" "grant-ws58-quarters-$last.sh"; then return 0; fi
  # the newest .sh may itself never have been started (its pid file absent): start it rather than generating past it
  if [ ! -e "${F}grant-ws58-quarters-$last.pid" ]; then dst="${F}grant-ws58-quarters-$last.sh"; next=$last; mk="${S}started-quarters-$last"; [ -e "$mk" ] && return 0; fi
  cap1=$(date -u -d "${next:0:4}-${next:4:2}-${next:6:2} +1 day" +%Y-%m-%d)T06:00:00Z
  [ "$(date -u -d "$cap1" +%s)" -le "$STOP_AT" ] || { log "SUCCESSION: next quarter cap $cap1 is past keeper stop; not generating"; return 0; }
  if [ ! -e "$dst" ]; then
    src="${F}grant-ws58-quarters-$last.sh"
    cap0="${next:0:4}-${next:4:2}-${next:6:2}T06:00:00Z"
    s0="${next:0:4}-${next:4:2}-${next:6:2}T05:52:00Z"
    local prevs0; prevs0="${last:0:4}-${last:4:2}-${last:6:2}T05:52:00Z"
    log "GENERATE $dst from $src (names $last->$next, CAP $cap0->$cap1, start gate $prevs0->$s0)"
    if [ $DRY = 0 ]; then
      sed -e "s/$last/$next/g" -e "s/$cap0/$cap1/g" -e "s/$prevs0/$s0/g" \
          -e "1a # ws58-calendar-keeper $(date -u +%FT%TZ): successor of grant-ws58-quarters-$last.sh; start gated $s0, cap $cap1." "$src" | tee "$dst" >/dev/null
      chmod +x "$dst"
      bash -n "$dst" || { log "GENERATE FAILED bash -n $dst"; return 0; }
      grep -q "CAP=\$(date -u -d '$cap1'" "$dst" || { log "GENERATE FAILED: CAP line not $cap1 in $dst"; return 0; }
      [ -e "${F}ws58-quarters-$next.queue" ] || add "${F}ws58-quarters-$next.queue" "# ws58 ${next:4:2}-${next:6:2} quarter queue (id|launcher_pid|window_s|gib|regions); created by ws58-calendar-keeper"
    fi
  fi
  log "START quarter writer $dst (setsid; no live quarter writer)"
  [ $DRY = 1 ] && return 0
  touch "$mk"
  (cd /mnt/raid0/llm/tmp/compute-flags && setsid bash "$dst" </dev/null >/dev/null 2>&1 &)
}
