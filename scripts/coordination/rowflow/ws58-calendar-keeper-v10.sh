# ---------- quarter queue / writer discovery ----------
quarter_days() { ls ${F}ws58-quarters-2026????.queue 2>/dev/null | sed -n 's/.*ws58-quarters-\(2026[0-9]\{4\}\)\.queue$/\1/p' | sort; }
newest_writer_day() { ls ${F}grant-ws58-quarters-2026????.sh 2>/dev/null | sed -n 's/.*grant-ws58-quarters-\(2026[0-9]\{4\}\)\.sh$/\1/p' | sort | tail -1; }
live_quarter_writers() { local d; for d in $(ls ${F}grant-ws58-quarters-2026????.pid 2>/dev/null | sed -n 's/.*quarters-\(2026[0-9]\{4\}\)\.pid$/\1/p'); do
  writer_alive "${F}grant-ws58-quarters-$d.pid" "grant-ws58-quarters-$d.sh" && echo "$d"; done; }

# ---------- 1. carry-over ----------
carry_over() {
  local live newest d id lp win gib regs nq seen=""
  live=$(live_quarter_writers | sort | tail -1)
  [ -n "$live" ] || return 0
  newest=$live; nq="${F}ws58-quarters-$newest.queue"
  [ -e "$nq" ] || return 0
  for d in $(quarter_days); do
    [ "$d" \< "$newest" ] || continue
    while IFS='|' read -r id lp win gib regs; do
      case "$id" in ''|\#*) continue;; esac
      grep -qx "$id" "${F}ws58-quarters-$d.queue.done" 2>/dev/null && continue
      [ -e "${G}$id.complete" ] && continue
      alive "$lp" || continue
      grep -q "^$id|" "$nq" && continue
      case " $seen " in *" $id "*) continue;; esac
      local dd held=0; for dd in $(quarter_days); do [ "$dd" \< "$d" ] && continue; grep -qx "$id" "${F}ws58-quarters-$dd.queue.done" 2>/dev/null && held=1; done
      [ $held = 1 ] && continue
      local row status notes; row=$(fillers_row "$id"); IFS=$'\t' read -r _ _ notes status <<< "$row"
      case "$status" in COMPLETE*|BACKLOG*|DONE*|RETIRED*) log "CARRY-SKIP $id: FILLERS status=$status"; seen="$seen $id"; continue;; esac
      case "$notes" in *blocker=*) log "CARRY-SKIP $id: FILLERS notes carry blocker="; seen="$seen $id"; continue;; esac
      seen="$seen $id"
      log "CARRY $id ($d -> $newest): $id|$lp|$win|$gib|$regs"
      [ $DRY = 1 ] || add "$nq" "$id|$lp|$win|$gib|$regs"
    done < "${F}ws58-quarters-$d.queue"
  done
}

