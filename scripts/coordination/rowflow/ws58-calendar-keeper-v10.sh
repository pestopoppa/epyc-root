    return fs
def sha(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for ch in iter(lambda: f.read(1 << 20), b''): h.update(ch)
    return h.hexdigest()
def vault(name, root, files, filed_at):
    """returns (ok, msg). dry: only sizes."""
