#!/usr/bin/env python3
"""PROPOSED FILLER_RL adapter: capture the official region-lock's ORIGINAL wait.
This substitutes the launcher entry shim, never creates a nested claim.
"""
import hashlib
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from runner import checked_reference, digest, proc_identity, write_json, Refused

def provider_environment(inherited, own):
    environment={key:value for key,value in inherited.items()
        if key.startswith("FILLER_") and key!="FILLER_STUB_CMD"}
    environment.update(PATH="/usr/bin:/bin",HOME=str(Path(own)/"provider-home"),
        LANG="C.UTF-8",LC_ALL="C.UTF-8",TZ="UTC",PYTHONNOUSERSITE="1",
        PYTHONDONTWRITEBYTECODE="1",PYTHONPATH="",LD_LIBRARY_PATH="",LD_PRELOAD="",
        OMP_NUM_THREADS="1",OPENBLAS_NUM_THREADS="1",MKL_NUM_THREADS="1")
    return environment

def main():
    own=Path(__file__).resolve().parent
    approval_path=own/"MAIN-APPROVED-NATIVE-LAUNCH.json"
    approval=json.loads(approval_path.read_text())
    if (approval.get("status")!="MAIN_APPROVED_NATIVE" or approval.get("approved") is not True
            or approval.get("native_launch_approved") is not True):
        raise Refused("UNARMED native capture")
    if os.environ.get("FILLER_ID") != approval["row_id"]:
        raise Refused("wrong canonical row")
    provider=checked_reference(approval["canonical_region_lock"])
    for reference in approval["canonical_provider_files"].values(): checked_reference(reference)
    bootstrap=approval["canonical_provider_bootstrap"]
    actual={str(path) for path in Path(bootstrap["root"]).glob("*.pth")}
    actual.add(str(Path(bootstrap["root"])/"_virtualenv.py"))
    if actual!=set(bootstrap["files"]):raise Refused("native provider startup import set changed")
    context=own/"NATIVE_OWNER_LIVE.json"
    if context.exists() or (own/"NATIVE_OWNER_ORIGINAL_WAIT.json").exists():
        raise Refused("native attempt state exists; preserve original receipts")
    context_output=context.open("x")
    # Preserve precisely the command generated by official filler. No second booking.
    provider_env=provider_environment(os.environ,own)
    child=subprocess.Popen([str(provider),*sys.argv[1:]],env=provider_env)
    identity=proc_identity(child.pid)
    if not identity:
        child.wait()
        raise Refused("cannot establish original native child identity")
    record={"row_id":approval["row_id"],"approval_sha256":digest(approval_path),
        "producer_sha256":digest(__file__),"captured_owner_identity":identity[0],
        "canonical_grant_sha256":digest(Path("/mnt/raid0/llm/tmp/compute-flags/grants")/(approval["row_id"]+".grant")),
        "provider_environment":provider_env}
    with context_output:
        json.dump(record,context_output)
    seen=[]
    def cancel(number,frame):
        seen.append(number)
        current=proc_identity(child.pid)
        if current and current[0]==identity[0] and current[2]!="Z":
            child.send_signal(number)
    for number in (signal.SIGTERM,signal.SIGINT): signal.signal(number,cancel)
    wait=child.wait()
    write_json(own/"NATIVE_OWNER_ORIGINAL_WAIT.json", {**record,
        "popen_wait_returncode":wait,"source":"original canonical region-lock Popen.wait",
        "signals":seen,"policy_returncode":128+seen[0] if seen else wait})
    return 128+seen[0] if seen else wait

if __name__=="__main__":
    try: raise SystemExit(main())
    except (Refused,OSError,ValueError,KeyError) as error: raise SystemExit("REFUSED: "+str(error))
